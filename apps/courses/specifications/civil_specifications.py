def get_course_specification(course_code: str) -> Dict[str, Any]:
    """Retrieves full specification for a course by code."""
    code_clean = course_code.upper().strip()
    for spec in COURSE_SPECIFICATIONS:
        if spec['code'].upper() == code_clean:
            return spec
    return {}

