from django.contrib.auth.models import BaseUserManager
from apps.core.constants import UserRoleChoices

class CustomUserManager(BaseUserManager):
    def create_user(self, email, username, password=None, **extra_fields):
        if not email:
            raise ValueError('The Email field must be set')
        if not username:
            raise ValueError('The Username field must be set')

        email = self.normalize_email(email)
        extra_fields.setdefault('is_staff', False)
        extra_fields.setdefault('is_superuser', False)
        extra_fields.setdefault('role', UserRoleChoices.STUDENT)

        user = self.model(email=email, username=username, **extra_fields)
        if password:
            user.set_password(password)
        else:
            user.set_unusable_password()
        user.save(using=self._db)
        return user

    def create_superuser(self, email, username, password=None, **extra_fields):
        extra_fields.setdefault('is_staff', True)
        extra_fields.setdefault('is_superuser', True)
        extra_fields.setdefault('role', UserRoleChoices.SUPERADMIN)
        extra_fields.setdefault('is_verified', True)

        if extra_fields.get('is_staff') is not True:
            raise ValueError('Superuser must have is_staff=True.')
        if extra_fields.get('is_superuser') is not True:
            raise ValueError('Superuser must have is_superuser=True.')

        return self.create_user(email, username, password, **extra_fields)

    def instructors(self):
        return self.filter(role__in=[UserRoleChoices.INSTRUCTOR, UserRoleChoices.TEACHING_ASSISTANT])

    def students(self):
        return self.filter(role=UserRoleChoices.STUDENT)

    def institution_admins(self):
        return self.filter(role=UserRoleChoices.INSTITUTION_ADMIN)
